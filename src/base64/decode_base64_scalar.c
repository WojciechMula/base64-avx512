size_t decode_base64_scalar(uint8_t* dst, const uint8_t* src, size_t size, int ignore_whitespace) {

    // Locate the padding: at most two '=' at the end (white space may
    // surround them when it is ignored).
    size_t end = size;
    unsigned padding = 0;
    if (ignore_whitespace)
        while (end > 0 && decode_table[src[end - 1]] == WS)
            end--;
    if (end > 0 && src[end - 1] == '=') {
        padding = 1;
        end--;
        if (ignore_whitespace)
            while (end > 0 && decode_table[src[end - 1]] == WS)
                end--;
        if (end > 0 && src[end - 1] == '=') {
            padding = 2;
            end--;
        }
    }

    // Decode src[0, end); any '=' left in there is an error.
    uint8_t* out = dst;
    size_t i = 0;

    // Fast path: whole quanta of base64 characters.
    const size_t quanta = end / 4;
    for (size_t q = 0; q < quanta; q++, i += 4) {
        const uint32_t x = quantum_table_0[src[i + 0]] | quantum_table_1[src[i + 1]]
                         | quantum_table_2[src[i + 2]] | quantum_table_3[src[i + 3]];
        if (x >= 0x01000000)
            break; // white space or error: take the slow path
        out[0] = (uint8_t)(x >> 16);
        out[1] = (uint8_t)(x >> 8);
        out[2] = (uint8_t)x;
        out += 3;
    }

    // Slow path: one character at a time.
    uint32_t acc = 0;
    unsigned n = 0;
    for (/**/; i < end; i++) {
        const uint8_t v = decode_table[src[i]];
        if (v < 64) {
            acc = (acc << 6) | v;
            if (++n == 4) {
                out[0] = (uint8_t)(acc >> 16);
                out[1] = (uint8_t)(acc >> 8);
                out[2] = (uint8_t)acc;
                out += 3;
                n = 0;
                acc = 0;
            }
        } else if (v == WS && ignore_whitespace) {
            continue;
        } else {
            return BASE64_DECODE_ERROR;
        }
    }

    if (n == 1)
        return BASE64_DECODE_ERROR;
    if (padding != 0 && n + padding != 4)
        return BASE64_DECODE_ERROR;

    if (n == 2) {
        *out++ = (uint8_t)(acc >> 4);
    } else if (n == 3) {
        *out++ = (uint8_t)(acc >> 10);
        *out++ = (uint8_t)(acc >> 2);
    }

    return (size_t)(out - dst);
}
